CREATE OR REPLACE FUNCTION public.fn_registrar_evento_orcamento(
    p_automacao TEXT,
    p_customer_id UUID,
    p_orcamento_id UUID,
    p_deduplication_key TEXT
)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    v_is_active BOOLEAN;
    v_automations JSONB;
BEGIN
    IF p_automacao <> 'orcamento_enviado' THEN
        RAISE EXCEPTION 'Evento de orçamento inválido: %', p_automacao;
    END IF;

    SELECT CASE WHEN jsonb_typeof(config.automations) = 'array'
        THEN config.automations ELSE '[]'::jsonb END
    INTO v_automations
    FROM public.configuracoes_empresa AS config
    WHERE config.id = 'c0000000-0000-0000-0000-000000000000'::uuid;
    v_automations := coalesce(v_automations, '[]'::jsonb);

    IF jsonb_array_length(v_automations) = 0 THEN
        v_is_active := TRUE;
    ELSE
        SELECT EXISTS (
            SELECT 1 FROM jsonb_array_elements(v_automations) AS item
            WHERE item->>'event' = p_automacao
              AND item->'isActive' = 'true'::jsonb
              AND length(trim(coalesce(item->>'template', ''))) > 0
        ) INTO v_is_active;
    END IF;
    IF NOT v_is_active THEN RETURN; END IF;

    INSERT INTO public.automacoes_eventos (
        automacao, appointment_id, customer_id, orcamento_id, deduplication_key
    ) VALUES (
        p_automacao, NULL, p_customer_id, p_orcamento_id, p_deduplication_key
    ) ON CONFLICT (deduplication_key) DO NOTHING;
EXCEPTION WHEN OTHERS THEN
    RAISE WARNING 'Falha isolada ao registrar evento de orçamento %: %',
        p_automacao, SQLERRM;
    RETURN;
END;
$$;

REVOKE ALL ON FUNCTION public.fn_registrar_evento_orcamento(TEXT, UUID, UUID, TEXT)
FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION public.fn_trigger_orcamento_enviado()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
    IF OLD.status = 'rascunho' AND NEW.status = 'enviado' THEN
        PERFORM public.fn_registrar_evento_orcamento(
            'orcamento_enviado', NEW.cliente_id, NEW.id,
            'orcamento_enviado:' || NEW.id
        );
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trigger_orcamento_enviado
AFTER UPDATE OF status ON public.orcamentos
FOR EACH ROW EXECUTE FUNCTION public.fn_trigger_orcamento_enviado();

CREATE OR REPLACE FUNCTION public.fn_enviar_orcamento(p_orcamento_id UUID)
RETURNS UUID
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
    v_customer_id UUID;
    v_automations JSONB;
    v_is_active BOOLEAN;
BEGIN
    SELECT CASE WHEN jsonb_typeof(config.automations) = 'array'
        THEN config.automations ELSE '[]'::jsonb END
    INTO v_automations
    FROM public.configuracoes_empresa AS config
    WHERE config.id = 'c0000000-0000-0000-0000-000000000000'::uuid;
    v_automations := coalesce(v_automations, '[]'::jsonb);
    IF jsonb_array_length(v_automations) = 0 THEN
        v_is_active := TRUE;
    ELSE
        SELECT EXISTS (
            SELECT 1 FROM jsonb_array_elements(v_automations) AS item
            WHERE item->>'event' = 'orcamento_enviado'
              AND item->'isActive' = 'true'::jsonb
              AND length(trim(coalesce(item->>'template', ''))) > 0
        ) INTO v_is_active;
    END IF;
    IF NOT v_is_active THEN
        RAISE EXCEPTION 'A automação de envio de orçamento está desativada ou sem template';
    END IF;

    UPDATE public.orcamentos
    SET status = 'enviado'
    WHERE id = p_orcamento_id AND status = 'rascunho'
    RETURNING cliente_id INTO v_customer_id;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'O orçamento não está disponível para envio';
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM public.automacoes_eventos
        WHERE deduplication_key = 'orcamento_enviado:' || p_orcamento_id
          AND orcamento_id = p_orcamento_id
          AND customer_id = v_customer_id
    ) THEN
        RAISE EXCEPTION 'O evento de envio não foi confirmado no outbox';
    END IF;
    RETURN p_orcamento_id;
END;
$$;

REVOKE ALL ON FUNCTION public.fn_enviar_orcamento(UUID) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.fn_enviar_orcamento(UUID) TO authenticated, service_role;


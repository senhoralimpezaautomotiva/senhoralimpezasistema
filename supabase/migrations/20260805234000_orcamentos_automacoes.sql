        ), 3)
), missing AS (
    SELECT defaults.item, defaults.position
    FROM defaults
    WHERE NOT EXISTS (
        SELECT 1
        FROM public.configuracoes_empresa AS config,
             jsonb_array_elements(CASE WHEN jsonb_typeof(config.automations) = 'array'
                 THEN config.automations ELSE '[]'::jsonb END) AS existing(item)
        WHERE config.id = 'c0000000-0000-0000-0000-000000000000'::uuid
          AND existing.item->>'event' = defaults.item->>'event'
    )
), missing_array AS (
    SELECT coalesce(jsonb_agg(item ORDER BY position), '[]'::jsonb) AS items FROM missing
)
UPDATE public.configuracoes_empresa AS config
SET automations = (CASE WHEN jsonb_typeof(config.automations) = 'array'
        THEN config.automations ELSE '[]'::jsonb END) || missing_array.items,
    updated_at = now()
FROM missing_array
WHERE config.id = 'c0000000-0000-0000-0000-000000000000'::uuid
  AND jsonb_array_length(missing_array.items) > 0;

UPDATE public.usuarios AS usuario
SET permissions = coalesce(usuario.permissions, '{}'::jsonb) || jsonb_build_object(
    'orcamentos', CASE usuario.perfil
        WHEN 'admin' THEN '{"view":true,"create":true,"edit":true,"delete":true}'::jsonb
        WHEN 'gerente' THEN '{"view":true,"create":true,"edit":true,"delete":true}'::jsonb
        WHEN 'atendente' THEN '{"view":true,"create":true,"edit":true,"delete":false}'::jsonb
        WHEN 'tecnico' THEN '{"view":true,"create":false,"edit":false,"delete":false}'::jsonb
        ELSE '{"view":false,"create":false,"edit":false,"delete":false}'::jsonb
    END
)
WHERE NOT coalesce(usuario.permissions, '{}'::jsonb) ? 'orcamentos';

